const HANABI_READING_KEYS=Object.keys(HANABI_READINGS).filter(k=>k!=='なし').sort((a,b)=>b.length-a.length);
function hanabiReading(name){
  const src=String(name||'').replace(/\s+/g,'');
  let pos=0,parts=[];
  while(pos<src.length){
    const word=HANABI_READING_KEYS.find(k=>src.startsWith(k,pos));
    if(word){parts.push({word,reading:HANABI_READINGS[word]});pos+=word.length;continue;}
    // 勝手な読みを振らず、未登録の固有名はそのまま表示して確認対象にする。
    parts.push({word:src[pos],reading:''});pos++;
  }
  let reading=parts.map(p=>p.reading||'').join('');
  const unknown=parts.filter(p=>!p.reading).map(p=>p.word).join('');
  // 単独の「菊」は「きく」。他の語の末尾の「菊」は「ぎく」と読む。
  if(reading && src!=='菊'){
    for(let i=0;i<parts.length;i++){
      if(parts[i].word==='菊' && i>0 && (parts[i-1].reading||'').length){
        const before=parts.slice(0,i).map(p=>p.reading).join('');
        // 花火用語の複合名として末尾に接続した場合だけ連濁
        if(before.endsWith('へんか')||before.endsWith('てんめつ')||before.endsWith('そめわけ')||before.endsWith('ひき'))parts[i].reading='ぎく';
      }
    }
    reading=parts.map(p=>p.reading).join('');
  }
  return {reading,unknown,complete:unknown.length===0};
}
